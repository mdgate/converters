const RCON = Uint8Array.from([0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]);

export function aes128EcbDecrypt(cipher: Uint8Array, key: Uint8Array): Uint8Array {
  const n = cipher.length - (cipher.length % 16);
  const roundKeys = expandKey(key);
  const out = new Uint8Array(n);
  const block = new Uint8Array(16);
  for (let i = 0; i < n; i += 16) {
    block.set(cipher.subarray(i, i + 16));
    decryptBlock(block, roundKeys);
    out.set(block, i);
  }
  return out;
}

function expandKey(key: Uint8Array): Uint8Array {
  const w = new Uint8Array(176);
  w.set(key.subarray(0, 16));
  for (let i = 16, r = 1; i < 176; i += 4) {
    let a = w[i - 4]!;
    let b = w[i - 3]!;
    let c = w[i - 2]!;
    let d = w[i - 1]!;
    if (i % 16 === 0) {
      const t = a;
      a = (SBOX[b]! ^ RCON[r++]!) & 0xff;
      b = SBOX[c]!;
      c = SBOX[d]!;
      d = SBOX[t]!;
    }
    w[i] = w[i - 16]! ^ a;
    w[i + 1] = w[i - 15]! ^ b;
    w[i + 2] = w[i - 14]! ^ c;
    w[i + 3] = w[i - 13]! ^ d;
  }
  return w;
}

function decryptBlock(s: Uint8Array, w: Uint8Array): void {
  addRoundKey(s, w, 10);
  for (let round = 9; round >= 1; round -= 1) {
    invShiftRows(s);
    invSubBytes(s);
    addRoundKey(s, w, round);
    invMixColumns(s);
  }
  invShiftRows(s);
  invSubBytes(s);
  addRoundKey(s, w, 0);
}

function addRoundKey(s: Uint8Array, w: Uint8Array, round: number): void {
  const off = round * 16;
  for (let i = 0; i < 16; i += 1) s[i] ^= w[off + i]!;
}

function invSubBytes(s: Uint8Array): void {
  for (let i = 0; i < 16; i += 1) s[i] = INV_SBOX[s[i]!]!;
}

function invShiftRows(s: Uint8Array): void {
  let t = s[13]!;
  s[13] = s[9]!;
  s[9] = s[5]!;
  s[5] = s[1]!;
  s[1] = t;
  t = s[2]!;
  s[2] = s[10]!;
  s[10] = t;
  t = s[6]!;
  s[6] = s[14]!;
  s[14] = t;
  t = s[3]!;
  s[3] = s[7]!;
  s[7] = s[11]!;
  s[11] = s[15]!;
  s[15] = t;
}

function invMixColumns(s: Uint8Array): void {
  for (let c = 0; c < 4; c += 1) {
    const i = c * 4;
    const a = s[i]!;
    const b = s[i + 1]!;
    const c1 = s[i + 2]!;
    const d = s[i + 3]!;
    s[i] = mul(a, 14) ^ mul(b, 11) ^ mul(c1, 13) ^ mul(d, 9);
    s[i + 1] = mul(a, 9) ^ mul(b, 14) ^ mul(c1, 11) ^ mul(d, 13);
    s[i + 2] = mul(a, 13) ^ mul(b, 9) ^ mul(c1, 14) ^ mul(d, 11);
    s[i + 3] = mul(a, 11) ^ mul(b, 13) ^ mul(c1, 9) ^ mul(d, 14);
  }
}

function mul(a: number, b: number): number {
  let p = 0;
  for (let i = 0; i < 8; i += 1) {
    if ((b & 1) !== 0) p ^= a;
    const hi = (a & 0x80) !== 0;
    a = (a << 1) & 0xff;
    if (hi) a ^= 0x1b;
    b >>= 1;
  }
  return p;
}
